"""Canonical dataset validation entry point.

    python -m lungai.data.validate [--data-root PATH] [--skip-files] [--out artifacts/data_validation]

Writes ``data_validation_report.json`` (machine-readable) and ``data_validation_report.md``.
Exit code 0 when no check fails, 1 when any check fails (warnings and blocked checks are reported).
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
from datetime import datetime, timezone
from pathlib import Path
from typing import Any, Dict, List

import pandas as pd

from lungai import __version__
from lungai.config import (
    CLASS_NAMES, DATASET, EXTERNAL_COHORT, REPO_ROOT, data_root, manifest_path, sha256_file,
)
from lungai.data import checks
from lungai.data.manifest import class_distribution, counts_by_split, load_manifest

logger = logging.getLogger("lungai.data.validate")
DEFAULT_OUT = REPO_ROOT / "artifacts" / "data_validation"


def _external_ids(root: Path) -> Dict[str, Any]:
    meta = root / EXTERNAL_COHORT["metadata_csv"]
    if not meta.is_file():
        return {"status": "blocked", "reason": "external cohort metadata not present under the data root", "ids": []}
    m = pd.read_csv(meta)
    normal = m[EXTERNAL_COHORT["finding_column"]] == EXTERNAL_COHORT["normal_value"]
    img_dir = root / EXTERNAL_COHORT["image_dir"]
    present = int(sum((img_dir / s).is_file() for s in m[EXTERNAL_COHORT["id_column"]]))
    return {
        "status": "pass",
        "rows": int(len(m)), "normal": int(normal.sum()), "abnormal": int((~normal).sum()),
        "images_present": present,
        "ids": m[EXTERNAL_COHORT["id_column"]].astype(str).tolist(),
    }


def build_report(skip_files: bool = False, root: Path | None = None) -> Dict[str, Any]:
    root = root or data_root()
    path = manifest_path()
    df = load_manifest(path)
    ext = _external_ids(root)

    results: Dict[str, Dict[str, Any]] = {
        "patient_leakage": checks.check_patient_leakage(df),
        "exact_duplicates": checks.check_exact_duplicates(df),
        "perceptual_duplicates": checks.check_perceptual_duplicates(df),
        "external_isolation": checks.check_external_isolation(df, ext.get("ids", [])),
        "label_source_confounding": checks.check_label_source_confounding(df),
        "proxy_labels": checks.check_proxy_labels(df),
        "placeholder_metadata": checks.check_placeholder_metadata(df),
        "absolute_paths": checks.check_absolute_paths(df),
        "image_files": {"status": "blocked", "reason": "skipped (--skip-files)"} if skip_files else checks.check_files(df, root),
    }
    overall, statuses = checks.summarize_status(results)
    grouped = checks.add_patient_groups(df)
    split_counts = counts_by_split(df)
    for split, c in split_counts.items():
        c["derived_patient_groups"] = int(grouped[grouped["split"] == split]["patient_group"].nunique())

    return {
        "report": "LungAI dataset validation",
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "lungai_version": __version__,
        "dataset_version": DATASET["version"],
        "manifest": DATASET["manifest"],
        "manifest_sha256_lf": sha256_file(path, normalize_newlines=True),
        "data_root_has_images": results["image_files"]["status"] not in ("blocked",),
        "class_order": CLASS_NAMES,
        "totals": {
            "images": int(len(df)),
            "unique_manifest_patient_ids": int(df["patient_id"].nunique()),
            "unique_derived_patient_groups": int(grouped["patient_group"].nunique()),
            "sources": {k: int(v) for k, v in df["source_dataset"].value_counts().sort_index().items()},
        },
        "splits": split_counts,
        "class_distribution": class_distribution(df),
        "external_cohort": {k: v for k, v in ext.items() if k != "ids"},
        "overall_status": overall,
        "check_status": statuses,
        "checks": results,
    }


def render_markdown(r: Dict[str, Any]) -> str:
    L: List[str] = [
        "# LungAI dataset validation report",
        "",
        f"- Generated: {r['generated_at']} (lungai {r['lungai_version']})",
        f"- Dataset: {r['dataset_version']} — `{r['manifest']}`",
        f"- Manifest SHA-256 (LF-normalised): `{r['manifest_sha256_lf']}`",
        f"- Overall status: **{r['overall_status'].upper()}**",
        "",
        "Generated by `python -m lungai.data.validate`. Do not edit by hand.",
        "",
        "## Partitions",
        "",
        "| Partition | Images | Manifest patient IDs | Derived patient groups |",
        "|---|---:|---:|---:|",
    ]
    for split, c in r["splits"].items():
        L.append(f"| {split} | {c['images']:,} | {c['patient_ids']:,} | {c['derived_patient_groups']:,} |")
    t = r["totals"]
    L += [f"| **total** | **{t['images']:,}** | **{t['unique_manifest_patient_ids']:,}** | **{t['unique_derived_patient_groups']:,}** |", ""]
    L += ["## Class distribution", "", "| Class | train | val | test | total |", "|---|---:|---:|---:|---:|"]
    for cls, c in r["class_distribution"].items():
        L.append(f"| {cls} | {c['train']:,} | {c['val']:,} | {c['test']:,} | {sum(c.values()):,} |")
    L += ["", "## Checks", "", "| Check | Status |", "|---|---|"]
    for k, s in r["check_status"].items():
        L.append(f"| {k} | {s.upper()} |")
    pl = r["checks"]["patient_leakage"]["by_derived_patient_group"]
    L += [
        "",
        "### Patient leakage (derived groups)",
        "",
        f"- Patient groups spanning splits: {pl['keys_spanning_splits']}",
        f"- Test images whose patient also has a training image: {pl['test_images_sharing_key_with_train']}"
        f" (by source: {pl['test_images_sharing_key_with_train_by_source']})",
        f"- Validation images whose patient also has a training image: {pl['val_images_sharing_key_with_train']}",
        f"- Rows with a synthetic per-image patient id: {r['checks']['patient_leakage']['rows_with_synthetic_per_image_patient_id']:,}",
        "",
        "Full evidence for every check is in `data_validation_report.json`.",
        "",
    ]
    return "\n".join(L)


def main(argv: List[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data-root", type=Path, default=None, help="folder containing data/raw and data/downloads")
    ap.add_argument("--skip-files", action="store_true", help="skip per-image existence/md5/decode checks")
    ap.add_argument("--out", type=Path, default=DEFAULT_OUT)
    args = ap.parse_args(argv)
    logging.basicConfig(level=logging.INFO, format="%(levelname)s %(name)s: %(message)s")

    report = build_report(skip_files=args.skip_files, root=args.data_root.resolve() if args.data_root else None)
    args.out.mkdir(parents=True, exist_ok=True)
    (args.out / "data_validation_report.json").write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
    (args.out / "data_validation_report.md").write_text(render_markdown(report), encoding="utf-8")
    logger.info("overall=%s checks=%s", report["overall_status"], report["check_status"])
    logger.info("wrote %s", args.out)
    return 1 if report["overall_status"] == "fail" else 0


if __name__ == "__main__":
    sys.exit(main())
