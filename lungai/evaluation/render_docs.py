"""Render the current model's results into the documentation, from generated artifacts only.

    python -m lungai.evaluation.render_docs

Inputs: artifacts/evaluation_reports/model_metrics.json (lungai.evaluation.served_metrics),
runs/<run>/run_metadata.json and data/derived/<build>/v6_build_report.json.
Outputs: docs/results/current_model.md (complete), and the text between
``<!-- BEGIN GENERATED: <name> -->`` and ``<!-- END GENERATED: <name> -->`` in the files of TARGETS.
Text outside the markers is never touched.
"""

from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from typing import Any, Dict, List, Optional

from lungai.config import CLASS_NAMES, REPO_ROOT

METRICS = REPO_ROOT / "artifacts" / "evaluation_reports" / "model_metrics.json"
FULL = REPO_ROOT / "docs" / "results" / "current_model.md"
TARGETS = {"README.md": "summary", "docs/model_card.md": "summary", "docs/experiment_results.md": "full"}
SHORT = {"COVID-19": "COVID-19", "Pleural Effusion": "Effusion", "Pulmonary Nodule / Mass": "Nodule/Mass", "Tuberculosis": "TB"}


def _pct(v: Optional[float]) -> str:
    return "—" if v is None else f"{v * 100:.1f}%"


def _ci(c: Optional[Dict[str, Any]]) -> str:
    return "" if not c or c.get("lower") is None else f"{c['lower'] * 100:.1f}–{c['upper'] * 100:.1f}%"


def _frac(c: Dict[str, Any]) -> str:
    return f"{c['successes']}/{c['n']} ({_pct(c['estimate'])}, 95% CI {_ci(c)})"


def _table(head: List[str], rows: List[List[Any]]) -> str:
    out = ["| " + " | ".join(head) + " |", "|" + "|".join("---" if i == 0 else "---:" for i in range(len(head))) + "|"]
    out += ["| " + " | ".join(str(x) for x in r) + " |" for r in rows]
    return "\n".join(out)


def load(metrics_path: Path = METRICS) -> Dict[str, Any]:
    r = json.loads(metrics_path.read_text(encoding="utf-8"))
    run = REPO_ROOT / "runs" / r["training"]["run_name"] / "run_metadata.json"
    build = REPO_ROOT / "data" / "derived" / r["build"] / "v6_build_report.json"
    r["_run"] = json.loads(run.read_text(encoding="utf-8")) if run.is_file() else None
    r["_build"] = json.loads(build.read_text(encoding="utf-8")) if build.is_file() else None
    return r


def summary(r: Dict[str, Any]) -> str:
    m, e, v = r["internal_test"]["metrics"], r["external"], r["validation_evidence"]
    b = e["binary_abnormality"]
    lines = [
        f"_Generated by `python -m lungai.evaluation.render_docs` from `artifacts/evaluation_reports/model_metrics.json` "
        f"({r['generated_at']}). Do not edit by hand._",
        "",
        f"**{r['canonical_model']['display_name']} {r['canonical_model']['version']}**, dataset {r['dataset_version']} "
        f"(`{r['build']}`), checkpoint `{r['canonical_model']['checkpoint_file']}` "
        f"(SHA-256 `{r['canonical_model']['checkpoint_sha256'][:12]}…`).",
        "",
        _table(["Split", "N", "Accuracy (95% CI)", "Macro F1", "Macro ROC-AUC"], [
            ["Validation (checkpoint selection)", v["n"], _pct(v["accuracy"]), _pct(v["macro_f1"]), f"{v['macro_roc_auc']:.3f}"],
            ["Test (evaluated once)", r["internal_test"]["n"], f"{_pct(m['accuracy'])} ({_ci(m['accuracy_ci95'])})",
             _pct(m["macro_f1"]), f"{m['macro_roc_auc']:.3f}"],
        ]),
        "",
        f"External, Montgomery County (N={e['n']}, normal vs TB only, evaluated once): TB scans flagged abnormal "
        f"{_frac(b['sensitivity'])}; normal scans called Normal {_frac(b['specificity'])}; TB scans called Tuberculosis "
        f"{_frac(e['exact_tuberculosis_recall'])}; ROC-AUC of P(abnormal) {b['roc_auc_p_abnormal']:.3f}.",
        "",
        f"Evidence: {r['evidence_level']}",
    ]
    if r.get("historical"):
        h = r["historical"]
        lines += ["", f"Previous model {h['model']['version']} (dataset {h['dataset_version']}, history only): internal test accuracy "
                      f"{_pct(h['internal_test']['metrics']['accuracy'])} (N={h['internal_test']['n']}), external sensitivity "
                      f"{h['external_binary_abnormality']['sensitivity']['successes']}/{h['external_binary_abnormality']['sensitivity']['n']} "
                      f"with specificity {h['external_binary_abnormality']['specificity']['successes']}/"
                      f"{h['external_binary_abnormality']['specificity']['n']}. {h['note']}"]
    return "\n".join(lines)


def full(r: Dict[str, Any]) -> str:
    m, e = r["internal_test"]["metrics"], r["external"]
    parts = [summary(r), "", "### Dataset composition"]
    bld = r.get("_build")
    if bld:
        splits = ["train", "val", "test"]
        rows = [[c] + [bld["counts"].get(s, {}).get(c, 0) for s in splits] for c in CLASS_NAMES]
        rows.append(["**Total**"] + [sum(bld["counts"].get(s, {}).values()) for s in splits])
        parts += ["", _table(["Class", "Train", "Val", "Test"], rows), "",
                  f"Sources: {', '.join(bld['sources_used'])}. Leakage checks: {json.dumps(bld['leakage'])}; "
                  f"near-duplicate pairs merged into one split group: {bld['near_duplicate_pairs']}. {bld['caveat']}"]
        src = sorted({k.split('|')[0] for k in bld["by_source_split"]})
        parts += ["", _table(["Source", "Train", "Val", "Test", "External", "Excluded"],
                             [[s] + [bld["by_source_split"].get(f"{s}|{x}", 0) for x in ("train", "val", "test", "external", "excluded")] for s in src])]
    else:
        parts += ["", "_Build report not available on this machine._"]
    run = r.get("_run")
    parts += ["", "### Training"]
    if run:
        parts += ["", f"Run `{run['run_name']}`, seed {run['seed']}, {run['train_images']} training images, "
                      f"{run['steps_per_epoch']} steps per epoch, started {run['started_at']}, finished {run['finished_at']}; "
                      f"stop reason: {run['stop_reason']}. {run['environment'].get('note', '')}",
                  "", _table(["Epoch", "Phase", "Train loss", "Val accuracy", "Val macro F1", "Val macro ROC-AUC", "Seconds"],
                             [[h["epoch"], h["phase"], f"{h['train_loss']:.4f}", _pct(h["val_accuracy"]), _pct(h["val_macro_f1"]),
                               f"{h['val_macro_roc_auc']:.3f}", h["seconds"]] for h in run["history"]]),
                  "", f"Selected checkpoint: epoch {run['selected']['epoch']} (best validation macro F1)."]
    pc = m["per_class"]
    parts += ["", "### Test split, per class", "",
              _table(["Class", "Support", "Precision", "Recall (95% CI)", "Specificity", "F1", "ROC-AUC"],
                     [[c, pc[c]["support"], _pct(pc[c]["precision"]), f"{_pct(pc[c]['recall'])} ({_ci(pc[c]['recall_ci95'])})",
                       _pct(pc[c]["specificity"]), _pct(pc[c]["f1"]), f"{pc[c]['roc_auc']:.3f}"] for c in CLASS_NAMES]),
              "", f"Weighted F1 {_pct(m['weighted_f1'])}; macro PR-AUC {m['macro_pr_auc']:.3f}; expected calibration error "
                  f"{m['calibration']['ece']:.3f} ({m['calibration']['n_bins']} bins); mean top-class score "
                  f"{m['calibration']['mean_confidence_correct']:.3f} when correct, {m['calibration']['mean_confidence_incorrect']:.3f} when wrong.",
              "", "Confusion matrix (rows = true class, columns = predicted, class order as above):", "",
              _table(["True \\ Pred"] + [SHORT.get(c, c) for c in CLASS_NAMES],
                     [[c] + list(row) for c, row in zip(CLASS_NAMES, m["confusion_matrix"])])]
    ps = r["internal_test"].get("per_source") or {}
    if ps:
        parts += ["", "### Test split, per source", "",
                  "Accuracy within each source, and recall for each class that source contributes. A source that is the only "
                  "provider of a class can be recognised by its image style rather than by disease.", "",
                  _table(["Source", "N", "Accuracy", "Recall by class"],
                         [[s, d.get("n", "—"), _pct(d.get("accuracy")),
                           ", ".join(f"{c} {_pct(v)}" for c, v in (d.get("recall_by_class") or {}).items())] for s, d in sorted(ps.items())])]
    parts += ["", "### External cohort: what the model predicted", "",
              _table(["True label", "Predicted counts"],
                     [[k, ", ".join(f"{p}: {n}" for p, n in sorted(v.items(), key=lambda x: -x[1]))] for k, v in e["prediction_breakdown"].items()]),
              "", e["interpretation"]]
    return "\n".join(parts)


SHARED = REPO_ROOT / "docs" / "manuscripts" / "shared"
MACRO_CLASS = {"COVID-19": "Covid", "Normal": "Normal", "Pleural Effusion": "Effusion", "Pneumonia": "Pneumonia",
               "Pulmonary Nodule / Mass": "Nodule", "Tuberculosis": "TB"}
SOURCE_MACRO = {"nih_cxr14": "NIH", "kermany": "Kermany", "shenzhen": "Shenzhen", "cohen_covid": "Cohen",
                "tbx11k": "TBXk", "covid_radiography": "CovidRad"}  # LaTeX macro names cannot contain digits


def flat_results(r: Dict[str, Any]) -> Dict[str, str]:
    """Every number the manuscripts, report and slides may quote, as display strings keyed by macro name."""
    m, e, v = r["internal_test"]["metrics"], r["external"], r["validation_evidence"]
    b = e["binary_abnormality"]
    p1 = lambda x: f"{x * 100:.1f}"  # noqa: E731  percent without the sign
    out = {
        "ModelVersion": r["canonical_model"]["version"], "DatasetBuild": r["build"],
        "CheckpointShort": r["canonical_model"]["checkpoint_sha256"][:12], "Seed": str(r["training"]["seed"]),
        "NTrain": f"{r['training']['train_images']:,}", "NVal": f"{v['n']:,}", "NTest": f"{r['internal_test']['n']:,}",
        "NExternal": str(e["n"]), "SelectedEpoch": str(v["selected_epoch"]), "EpochsTrained": str(v["epochs_trained"]),
        "ValAcc": p1(v["accuracy"]), "ValMacroFOne": p1(v["macro_f1"]), "ValMacroAUC": f"{v['macro_roc_auc']:.3f}",
        "TestAcc": p1(m["accuracy"]), "TestAccLo": p1(m["accuracy_ci95"]["lower"]), "TestAccHi": p1(m["accuracy_ci95"]["upper"]),
        "TestMacroFOne": p1(m["macro_f1"]), "TestWeightedFOne": p1(m["weighted_f1"]), "TestMacroRecall": p1(m["macro_recall"]),
        "TestMacroPrecision": p1(m["macro_precision"]), "TestMacroAUC": f"{m['macro_roc_auc']:.3f}",
        "TestMacroPRAUC": f"{m['macro_pr_auc']:.3f}", "TestECE": f"{m['calibration']['ece']:.3f}",
        "ExtSensK": str(b["sensitivity"]["successes"]), "ExtSensN": str(b["sensitivity"]["n"]), "ExtSens": p1(b["sensitivity"]["estimate"]),
        "ExtSensLo": p1(b["sensitivity"]["lower"]), "ExtSensHi": p1(b["sensitivity"]["upper"]),
        "ExtSpecK": str(b["specificity"]["successes"]), "ExtSpecN": str(b["specificity"]["n"]), "ExtSpec": p1(b["specificity"]["estimate"]),
        "ExtSpecLo": p1(b["specificity"]["lower"]), "ExtSpecHi": p1(b["specificity"]["upper"]),
        "ExtAUC": f"{b['roc_auc_p_abnormal']:.3f}", "ExtTBK": str(e["exact_tuberculosis_recall"]["successes"]),
        "ExtTBN": str(e["exact_tuberculosis_recall"]["n"]), "ExtTB": p1(e["exact_tuberculosis_recall"]["estimate"]),
        "ExtCovidCalls": str(sum(v2.get("COVID-19", 0) for v2 in e["prediction_breakdown"].values())),
    }
    for c in CLASS_NAMES:
        k, pc = MACRO_CLASS[c], m["per_class"][c]
        out.update({f"Support{k}": str(pc["support"]), f"Precision{k}": p1(pc["precision"]), f"Recall{k}": p1(pc["recall"]),
                    f"Specificity{k}": p1(pc["specificity"]), f"FOne{k}": p1(pc["f1"]), f"AUC{k}": f"{pc['roc_auc']:.3f}"})
    for s, d in (r["internal_test"].get("per_source") or {}).items():
        k = SOURCE_MACRO.get(s, "".join(w.capitalize() for w in s.split("_")))
        out.update({f"SrcN{k}": str(d["n"]), f"SrcAcc{k}": p1(d["accuracy"])})
    cmp_path = REPO_ROOT / "artifacts" / "evaluation_reports" / "run_comparison.json"
    if cmp_path.is_file():
        c = json.loads(cmp_path.read_text(encoding="utf-8"))
        out.update({"CmpN": f"{c['n_common']:,}", "CmpSelected": c["selected_run"],
                    "CmpMcNemarB": str(c["mcnemar_all"]["a_right_b_wrong"]), "CmpMcNemarC": str(c["mcnemar_all"]["a_wrong_b_right"]),
                    "CmpMcNemarP": f"{c['mcnemar_all']['p_value_exact']:.3g}"})
        for side, name in (("a", "RunOne"), ("b", "RunTwo")):
            for subset, tag in (("all", ""), ("shared_sources_only", "Shared")):
                mm = c[side][subset]
                out.update({f"Cmp{name}{tag}N": f"{mm['n']:,}", f"Cmp{name}{tag}Acc": p1(mm["accuracy"]),
                            f"Cmp{name}{tag}MacroFOne": p1(mm["macro_f1"])})
                if "macro_roc_auc" in mm:
                    out[f"Cmp{name}{tag}MacroAUC"] = f"{mm['macro_roc_auc']:.3f}"
    # Accuracy has two intervals: Wilson (accuracy_ci95, the TestAccLo/Hi macros) and percentile bootstrap.
    bci = (m.get("bootstrap_ci95") or {}).get("accuracy")
    if bci:
        out.update({"TestAccBootLo": p1(bci["lower"]), "TestAccBootHi": p1(bci["upper"])})
    # CXR input gate: calibration (validation split) and rejection of real radiographs (test/external), from app checks
    checks = REPO_ROOT / "artifacts" / "app_checks"
    cal = checks / "cxr_gate_calibration_v6_build_002.json"
    if cal.is_file():
        c = json.loads(cal.read_text(encoding="utf-8"))
        out.update({"CxrGateNewThr": f"{c['heuristic_threshold']:.3f}", "CxrGateValN": f"{c['n']:,}",
                    "CxrGateValPassNew": p1(c["val_pass_rate_at_threshold"]), "CxrGateValPassOld": p1(c["val_pass_rate_at_0.83"])})
    for key, fname in (("BOneOld", "cxr_gate_rejection_v6_build_001.json"), ("BTwoNew", "cxr_gate_rejection_v6_build_002_heuristic0703.json"),
                       ("BTwoOld", "cxr_gate_rejection_v6_build_002_heuristic083.json")):
        f = checks / fname
        if f.is_file():
            g = json.loads(f.read_text(encoding="utf-8"))["total"]
            for split, tag in (("test", "Test"), ("external", "Ext")):
                n, k = g[split]["n"], g[split]["rejected"]
                out.update({f"CxrGate{key}{tag}Rej": f"{k:,}", f"CxrGate{key}{tag}N": f"{n:,}", f"CxrGate{key}{tag}RejPct": p1(k / n)})
    # Run 1 (superseded v6.0), from its own once-only evaluation reports, for the run comparison tables
    run1 = REPO_ROOT / "artifacts" / "evaluation_reports"
    if (run1 / "v6_test" / "metrics_test.json").is_file() and (run1 / "v6_external" / "metrics_external.json").is_file():
        t1 = json.loads((run1 / "v6_test" / "metrics_test.json").read_text(encoding="utf-8"))["result"]["metrics"]
        e1 = json.loads((run1 / "v6_external" / "metrics_external.json").read_text(encoding="utf-8"))["result"]
        b1 = e1["binary_abnormality"]
        out.update({"RunOneTestN": f"{t1['n']:,}", "RunOneTestAcc": p1(t1["accuracy"]), "RunOneTestMacroFOne": p1(t1["macro_f1"]),
                    "RunOneTestMacroAUC": f"{t1['macro_roc_auc_ovr']:.3f}",
                    "RunOneExtSensK": str(b1["sensitivity"]["successes"]), "RunOneExtSpecK": str(b1["specificity"]["successes"]),
                    "RunOneExtAUC": f"{b1['roc_auc_p_abnormal']:.3f}", "RunOneExtTBK": str(e1["exact_tuberculosis_recall"]["successes"]),
                    "RunOneExtCovidCalls": str(sum(v2.get("COVID-19", 0) for v2 in e1["prediction_breakdown"].values()))})
    probe_path = REPO_ROOT / "artifacts" / "data_quality" / f"source_probe_{r['build']}.json"
    if probe_path.is_file():
        pr = json.loads(probe_path.read_text(encoding="utf-8"))
        out.update({"ProbeNTrain": f"{pr['n_train']:,}", "ProbeNTest": f"{pr['n_test']:,}"})
        for ext, tag in (("imagenet", "Img"), ("model", "Mdl")):
            if ext not in pr:
                continue
            a = pr[ext]["all"]
            out.update({f"Probe{tag}BalAcc": p1(a["balanced_accuracy"]), f"Probe{tag}Chance": p1(a["chance"]),
                        f"Probe{tag}NSources": str(a["n_sources"])})
            for key, v in pr[ext].items():
                if key.startswith("within:"):
                    k = MACRO_CLASS[key.split(":", 1)[1]]
                    out.update({f"Probe{tag}Within{k}": p1(v["balanced_accuracy"]), f"Probe{tag}Within{k}Chance": p1(v["chance"]),
                                f"Probe{tag}Within{k}NSources": str(len(v["sources"]))})
    ms_path = REPO_ROOT / "artifacts" / "evaluation_reports" / "multi_seed_summary.json"
    if ms_path.is_file():
        ms = json.loads(ms_path.read_text(encoding="utf-8"))
        out["MSNRuns"] = str(len(ms["runs"]))
        out["MSSeeds"] = ", ".join(str(x["seed"]) for x in ms["runs"])
        names = {"test_accuracy": "TestAcc", "test_macro_f1": "TestMacroFOne", "test_macro_roc_auc": "TestMacroAUC",
                 "ext_sensitivity": "ExtSens", "ext_specificity": "ExtSpec", "ext_auc": "ExtAUC", "ext_exact_tb_recall": "ExtTB"}
        for k, tag in names.items():
            s = ms["summary"][k]
            fmt = (lambda x: f"{x:.3f}") if "auc" in k else p1
            out[f"MS{tag}Mean"], out[f"MS{tag}Min"], out[f"MS{tag}Max"] = fmt(s["mean"]), fmt(s["min"]), fmt(s["max"])
            out[f"MS{tag}SD"] = "n/a" if s["sd"] is None else fmt(s["sd"])
        # Per-run values in the order given to aggregate_seeds (macro names cannot contain digits)
        for word, run in zip(("One", "Two", "Three", "Four", "Five"), ms["runs"]):
            rv = run["values"]
            out.update({f"MSRun{word}Seed": str(run["seed"]), f"MSRun{word}TestAcc": p1(rv["test_accuracy"]),
                        f"MSRun{word}TestMacroFOne": p1(rv["test_macro_f1"]), f"MSRun{word}TestMacroAUC": f"{rv['test_macro_roc_auc']:.3f}",
                        f"MSRun{word}ExtSens": p1(rv["ext_sensitivity"]), f"MSRun{word}ExtSpec": p1(rv["ext_specificity"]),
                        f"MSRun{word}ExtTB": p1(rv["ext_exact_tb_recall"])})
        for i, a in enumerate(ms.get("ablation", []), start=1):
            av = a["values"]
            out.update({f"AblTestAcc": p1(av["test_accuracy"]), "AblTestMacroFOne": p1(av["test_macro_f1"]),
                        "AblTestMacroAUC": f"{av['test_macro_roc_auc']:.3f}", "AblExtSpec": p1(av["ext_specificity"]),
                        "AblExtSens": p1(av["ext_sensitivity"]), "AblExtTB": p1(av["ext_exact_tb_recall"])})
    h = r.get("historical")
    if h:
        out.update({"VFiveAcc": p1(h["internal_test"]["metrics"]["accuracy"]), "VFiveN": f"{h['internal_test']['n']:,}",
                    "VFiveExtSpecK": str(h["external_binary_abnormality"]["specificity"]["successes"]),
                    "VFiveExtSpecN": str(h["external_binary_abnormality"]["specificity"]["n"])})
    # Novelty extension (Spec/Inlp/Loso/Bs macros): merged only when artifacts/novelty/*.json exist
    from lungai.novelty.render_novelty import NOVELTY_JSONS, novelty_macros
    if any(p.is_file() for p in NOVELTY_JSONS):
        out.update(novelty_macros())
    return out


def write_shared(r: Dict[str, Any]) -> None:
    SHARED.mkdir(parents=True, exist_ok=True)
    flat = flat_results(r)
    (SHARED / "results.json").write_text(json.dumps({"_generated_from": "artifacts/evaluation_reports/model_metrics.json",
                                                     "_generated_at": r["generated_at"], **flat}, indent=2) + "\n", encoding="utf-8")
    tex = ["% Generated by python -m lungai.evaluation.render_docs from artifacts/evaluation_reports/model_metrics.json.",
           f"% Source generated_at {r['generated_at']}. Do not edit by hand.", "\\providecommand{\\xspace}{}"]
    tex += [f"\\newcommand{{\\R{k}}}{{{v.replace('_', chr(92) + '_')}}}" for k, v in flat.items()]
    (SHARED / "results_macros.tex").write_text("\n".join(tex) + "\n", encoding="utf-8")


def replace_block(path: Path, name: str, content: str) -> bool:
    raw = path.read_bytes().decode("utf-8")
    nl = "\r\n" if "\r\n" in raw else "\n"  # keep the file's own line endings
    pat = re.compile(rf"(<!-- BEGIN GENERATED: {name} -->).*?(<!-- END GENERATED: {name} -->)", re.S)
    if not pat.search(raw):
        return False
    body = content.replace("\n", nl)
    path.write_bytes(pat.sub(lambda mo: mo.group(1) + nl + body + nl + mo.group(2), raw).encode("utf-8"))
    return True


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--metrics", type=Path, default=METRICS)
    args = ap.parse_args(argv)
    r = load(args.metrics)
    FULL.parent.mkdir(parents=True, exist_ok=True)
    FULL.write_text(f"# Current model: results\n\n{full(r)}\n", encoding="utf-8")
    print(f"wrote {FULL.relative_to(REPO_ROOT)}")
    write_shared(r)
    print(f"wrote {(SHARED / 'results_macros.tex').relative_to(REPO_ROOT)} and results.json")
    missing = []
    for rel, block in TARGETS.items():
        ok = replace_block(REPO_ROOT / rel, block, summary(r) if block == "summary" else full(r))
        print(f"{rel}: {'updated' if ok else 'NO MARKERS (not changed)'}")
        missing += [] if ok else [rel]
    return 1 if missing else 0


if __name__ == "__main__":
    raise SystemExit(main())
